r"""Check that memory conditions B (documents) and C (graph) carry the same record-level information.

C to B: every string value on the record's own nodes (EXP, HYP, RES, FIND, FOLLOW), on the grouping nodes one edge
away (labels only), and in the provenance of the record's edges must appear in memory\documents\<id>.md.
B to C: every value line and section body of the document must appear among those graph strings.
Comparison is on whitespace-normalized, case-folded text. Writes audit\equivalence_check.md.
"""
import collections
import json
import os
import re

HB = r"C:\Users\lisas\OneDrive\Documents\Basketball\Research Harness Benchmark"
nodes = {n["id"]: n for n in map(json.loads, open(os.path.join(HB, "memory", "graph_nodes.jsonl"), encoding="utf-8"))}
edges = [json.loads(l) for l in open(os.path.join(HB, "memory", "graph_edges.jsonl"), encoding="utf-8")]
OWN = ("EXP:", "HYP:", "RES:", "FIND:", "FOLLOW:")
SKIP_PROV = {"rule", "record"}


def norm(s):
    return re.sub(r"\s+", " ", str(s)).strip().lower()


def flat(v):
    if isinstance(v, list):
        for x in v:
            yield from flat(x)
    elif isinstance(v, dict):
        for x in v.values():
            yield from flat(x)
    elif v not in (None, "") and not isinstance(v, bool):
        yield str(v)


by_rec = collections.defaultdict(list)
for e in edges:
    rec = e["provenance"].get("record")
    if rec:
        by_rec[rec].append(e)
    if "family" in e["provenance"] and e["dst"].startswith("EXP:"):
        by_rec[e["dst"][4:]].append(e)

ids = [n[4:] for n in nodes if n.startswith("EXP:")]
fails_cb, fails_bc = collections.Counter(), collections.Counter()
examples = collections.defaultdict(list)
for rid in ids:
    graph_strings = []
    for pre in OWN:
        n = nodes.get(pre + rid)
        if n:
            graph_strings += [s for k, v in n.items() if k not in ("id", "type", "source_record") for s in flat(v)]
    for e in by_rec[rid]:
        for end in (e["src"], e["dst"]):
            if end.startswith(OWN) and end.split(":", 1)[1] == rid:
                continue
            n = nodes.get(end)
            if n is not None:
                graph_strings += [str(n.get("label", ""))] if "label" in n else []
                if end.startswith("EXP:"):
                    graph_strings.append(end[4:])
        graph_strings += [s for k, v in e["provenance"].items() if k not in SKIP_PROV for s in flat(v)]
    graph_strings = [g for g in graph_strings if norm(g)]
    doc = open(os.path.join(HB, "memory", "documents", rid + ".md"), encoding="utf-8").read()
    ndoc = norm(doc)
    for g in graph_strings:
        if norm(g) not in ndoc and norm(g) != "see notes of " + rid.lower():
            fails_cb[rid] += 1
            examples["C not in B"].append(f"{rid}: {g[:90]}")
    gtext = " || ".join(norm(g) for g in graph_strings) + " || " + rid.lower()
    for line in doc.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if re.fullmatch(r"- [A-Z][\w -]+:", line):
            continue
        val = re.sub(r"^- (?:[A-Z][\w -]+: )?", "", line)
        if re.match(r"^SF\d+ \(", val):
            parts = [p for p in re.split(r"[ ,()]+|: ", val) if p]
        else:
            parts = re.split(r"; |, | \(|\)$", val)
        for p in parts:
            p = norm(p).strip(" ,")
            if p and p not in gtext:
                fails_bc[rid] += 1
                examples["B not in C"].append(f"{rid}: {p[:90]}")
out = ["# Equivalence check between memory conditions B and C (generated by scripts\\06_equivalence_check.py)", "",
       f"Records checked: {len(ids)}. Records with graph strings missing from the document: {len(fails_cb)} "
       f"({sum(fails_cb.values())} strings). Records with document values missing from the graph: {len(fails_bc)} "
       f"({sum(fails_bc.values())} values).", ""]
for k in ("C not in B", "B not in C"):
    out += [f"## {k} (first 40)", ""] + [f"- {x}" for x in examples[k][:40]] + [""]
open(os.path.join(HB, "audit", "equivalence_check.md"), "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out[:3]))
for k in ("C not in B", "B not in C"):
    print(k, collections.Counter(re.sub(r"^\S+ ", "", x)[:40] for x in examples[k]).most_common(12))
