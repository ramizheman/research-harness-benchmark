r"""Project x topic counts and cross-project links, for research_history_map.md.

Reads experiment_inventory.csv and memory\graph_edges.jsonl. Writes audit\project_links.md. Links are the
`extends` and `duplicates` edges between Experiment nodes; related-field links are unverified in direction.
"""
import collections
import csv
import json
import os

HB = r"C:\Users\lisas\OneDrive\Documents\Basketball\Research Harness Benchmark"
inv = {e["experiment_id"]: e for e in csv.DictReader(open(os.path.join(HB, "experiment_inventory.csv"), encoding="utf-8-sig"))}
reps = [e for e in inv.values() if e["experiment_id"] == e["study_family_representative"]]
edges = [json.loads(l) for l in open(os.path.join(HB, "memory", "graph_edges.jsonl"), encoding="utf-8")]


def proj(p):
    p = p.replace(" (supplementary audit)", "").replace(" / opponent scouting", "").replace(" / Lineup Adaptation", "")
    return {"Lineup/Team Adaptation": "Team Adaptation", "Playing-time / luck": "Halftime Minutes"}.get(p, p)


projects = [p for p, _ in collections.Counter(proj(e["project"]) for e in reps).most_common()]
topics = [t for t, _ in collections.Counter(e["domain_topic"] for e in reps).most_common()]
out = ["# Project links (generated by scripts\\07_project_links.py)", "", "## Project x topic (study families)", "",
       "| project | " + " | ".join(topics) + " |", "|" + "---|" * (len(topics) + 1)]
for p in projects:
    out.append(f"| {p} | " + " | ".join(str(sum(1 for e in reps if proj(e['project']) == p and e['domain_topic'] == t) or "") for t in topics) + " |")
link = collections.Counter()
for e in edges:
    if e["rel"] in ("extends", "duplicates") and e["src"].startswith("EXP:") and e["dst"].startswith("EXP:"):
        a, b = inv[e["src"][4:]], inv[e["dst"][4:]]
        pa, pb = proj(a["project"]), proj(b["project"])
        if pa != pb:
            kind = "study family" if "family" in e["provenance"] else "related-field reference"
            link[(tuple(sorted((pa, pb))), kind)] += 1
out += ["", "## Cross-project links", "", "| project A | project B | link type | edges |", "|---|---|---|---|"]
out += [f"| {a} | {b} | {k} | {n} |" for ((a, b), k), n in sorted(link.items(), key=lambda x: -x[1])]
open(os.path.join(HB, "audit", "project_links.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
