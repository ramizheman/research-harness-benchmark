r"""Automated preparation of the research history: question clusters, automated adjudication, knowability, dates, overlaps.

Inputs (read-only): memory\ledger_merged.jsonl, audit\study_family_review.csv, experiment_inventory.csv,
                    audit\duplicate_candidates_raw.tsv
Outputs: research_question_clusters.csv, automated_adjudication.csv,
         audit\date_audit.csv, audit\overlap_candidates.csv, audit\cluster_calibration.json, audit\adjudication_summary.md
"""
import collections
import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from bench import adjudicate, clusters, common  # noqa: E402

HB = common.HB
records = common.load_records()
by_id = {r["id"]: r for r in records}
family_of, members, kind, note = common.load_families(records)
inv = common.load_inventory()

# ---------------------------------------------------------------- question clusters
fam_rows, cl_rows, cal = clusters.build(records, family_of, members)
cal["related_field_agreement"] = clusters.related_field_agreement(records, fam_rows, family_of)
cluster_of = {r["study_family_id"]: r["cluster_id"] for r in fam_rows}
cl_by = {c["cluster_id"]: c for c in cl_rows}
fams, vec, X = clusters.family_matrix(records, family_of, members)
S = clusters.cosine(X)
fam_sim_pairs = {(fams[i], fams[j]): float(S[i, j]) for i in range(len(fams)) for j in range(i + 1, len(fams))
                 if S[i, j] >= cal["repeat_similarity"]}

# ---------------------------------------------------------------- adjudication
adj = adjudicate.adjudicate_all(records, family_of, members, kind, inv)
know = adjudicate.knowability(adj, records, family_of, members, cluster_of)
dates = adjudicate.date_audit(records)
date_by = {d["experiment_id"]: d for d in dates}
dup_rows = list(csv.DictReader(open(os.path.join(HB, "audit", "duplicate_candidates_raw.tsv"), encoding="utf-8"), delimiter="\t"))
ov = adjudicate.overlaps(records, family_of, members, fam_sim_pairs, dup_rows)
ov_by = collections.defaultdict(list)
for o in ov:
    ov_by[o["family_a"]].append(f"{o['family_b']} ({o['overlap_class']})")
    ov_by[o["family_b"]].append(f"{o['family_a']} ({o['overlap_class']})")
fam_rel = {r["study_family_id"]: r for r in fam_rows}
for a in adj:
    f = a["study_family_id"]
    ms = [m for m in members[f] if m in by_id]
    a.update(know[f])
    a["recorded_knowable_in_advance"] = "; ".join(f"{m}={by_id[m].get('knowable_in_advance') or 'missing'}" for m in ms)
    a["question_cluster"] = cluster_of[f]
    a["question_relation"] = fam_rel[f]["relation"]
    a["dates"] = "; ".join(f"{m}={by_id[m].get('date') or '?'} ({by_id[m].get('date_basis') or '?'})" for m in ms)
    a["date_reliable"] = "yes" if all(date_by[m]["reliable"] == "yes" for m in ms) else "no"
    a["earliest_date_low"] = min(date_by[m]["interval_low"] for m in ms)
    a["latest_date_high"] = max(date_by[m]["interval_high"] for m in ms)
    a["overlap_candidates"] = "; ".join(sorted(ov_by.get(f, [])))
    a["sources"] = " | ".join(str(s) for m in ms for s in by_id[m].get("sources") or [])
common.write_csv(common.safe_path(os.path.join(HB, "automated_adjudication.csv")), adj)

for r in fam_rows:
    c = cl_by[r["cluster_id"]]
    r.update({"cluster_label_terms": c["label_terms"], "cluster_main_topic": c["main_topic"],
              "cluster_mean_similarity": c["mean_within_similarity"], "cluster_families": c["families"],
              "automated_stratum": next(a["automated_stratum"] for a in adj if a["study_family_id"] == r["study_family_id"]),
              "method": f"TF-IDF unigram cosine, average linkage, merge similarity {cal['merge_similarity']}, repeat similarity {cal['repeat_similarity']}"})
common.write_csv(common.safe_path(os.path.join(HB, "research_question_clusters.csv")), fam_rows)
common.write_csv(os.path.join(HB, "audit", "date_audit.csv"), dates)
common.write_csv(os.path.join(HB, "audit", "overlap_candidates.csv"), ov or [{"family_a": "", "family_b": ""}])
json.dump(cal, open(os.path.join(HB, "audit", "cluster_calibration.json"), "w", encoding="utf-8"), indent=1)

# ---------------------------------------------------------------- reconciliation summary
rec_strata = collections.Counter(adjudicate.record_stratum(r)[0] for r in records)
fam_strata = collections.Counter(a["automated_stratum"] for a in adj)
cross = collections.Counter()
for a in adj:
    for m in a["members"].split("; "):
        cross[(a["automated_stratum"], adjudicate.record_stratum(by_id[m])[0])] += 1
rep_stratum = {a["study_family_id"]: adjudicate.record_stratum(by_id[a["representative"]])[0] for a in adj}
changed = [a for a in adj if a["automated_stratum"] != rep_stratum[a["study_family_id"]]]
cols = ["supported", "rejected", "untestable", "artifact", "uncertain", "not_a_test", "no_result", "mixed"]
L = ["# Automated adjudication summary (generated by scripts\\10_prepare_history.py)", "",
     "Automated, rule-based adjudication. Not independent human adjudication.", "",
     f"- Records: {len(records)}. Study families: {len(adj)}. Members summed over families: {sum(len(a['members'].split('; ')) for a in adj)}.",
     f"- Families whose members disagree on stratum: {sum(1 for a in adj if a['members_disagree'] == 'yes')}.",
     f"- Families whose automated stratum differs from the representative record's stratum: {len(changed)}.", "",
     "## Record-level strata", "", "| stratum | records |", "|---|---|"] + [f"| {k} | {rec_strata.get(k, 0)} |" for k in cols] + [
     f"| total | {sum(rec_strata.values())} |", "", "## Family-level automated strata", "", "| stratum | families |", "|---|---|"] + [
     f"| {k} | {fam_strata.get(k, 0)} |" for k in cols] + [f"| total | {sum(fam_strata.values())} |", "",
     "## Family stratum (rows) x member record stratum (columns), counted in records", "",
     "| family stratum | " + " | ".join(cols) + " | records |", "|---|" + "---|" * (len(cols) + 1)] + [
     f"| {fs} | " + " | ".join(str(cross[(fs, rs)]) for rs in cols) + f" | {sum(cross[(fs, rs)] for rs in cols)} |" for fs in cols] + [
     "", "## Decision rules applied", "", "| rule | families |", "|---|---|"] + [
     f"| {k} | {v} |" for k, v in collections.Counter(a["decision_rule"] for a in adj).most_common()] + [
     "", "## Confidence", "", "| level | families |", "|---|---|"] + [
     f"| {k} | {v} |" for k, v in collections.Counter(a["confidence_level"] for a in adj).most_common()] + [
     "", "## Validation status", "", "| status | all families | supported families |", "|---|---|---|"] + [
     f"| {k} | {v} | {sum(1 for a in adj if a['validation_status'] == k and a['automated_stratum'] == 'supported')} |"
     for k, v in collections.Counter(a["validation_status"] for a in adj).most_common()] + [
     "", "## Knowability recomputed from earlier information", "", "| automated | families |", "|---|---|"] + [
     f"| {k} | {v} |" for k, v in collections.Counter(a["knowable_auto"] for a in adj).most_common()] + [
     "", "## Automated knowability vs recorded knowable_in_advance (families with an applicable automated value; representative record)", "",
     "| automated \\ recorded | yes | no | unclear | missing |", "|---|---|---|---|---|"]
ka = collections.Counter((a["knowable_auto"], by_id[a["representative"]].get("knowable_in_advance") or "missing") for a in adj if a["knowable_auto"] != "not_applicable")
L += [f"| {k} | " + " | ".join(str(ka[(k, x)]) for x in ("yes", "no", "unclear", "missing")) + " |" for k in ("yes_from_history", "yes_from_history_probable", "yes_from_data", "no_evidence")]
L += ["", "## Dates", "", f"- Records with a reliable date (doc or transcript, no later date mentioned in text): {sum(1 for d in dates if d['reliable'] == 'yes')}.",
      f"- Records dated by file modification time (upper bound only): {sum(1 for d in dates if d['date_basis'] == 'mtime')}.",
      f"- Records whose text mentions a date later than the record date: {sum(1 for d in dates if 'later date' in d['issues'])}.",
      f"- Records in bulk modification-date groups (8 or more records share one date): {sum(1 for d in dates if 'share this modification date' in d['issues'])}.",
      f"- Records with no date: {sum(1 for d in dates if not d['date'])}.", "",
      "## Overlaps between families", "", f"- Candidate pairs: {len(ov)} (probable duplicates: {sum(1 for o in ov if o['overlap_class'] == 'probable_duplicate')}).", "",
      "## Question clusters", "", f"- Clusters: {len(cl_rows)}; families per cluster: " + ", ".join(f"{k}: {v}" for k, v in sorted(collections.Counter(c['n_families'] for c in cl_rows).items())) + ".",
      f"- Calibration: {json.dumps(cal)}", "",
      "## Families whose automated stratum differs from the representative record", "",
      "| family | representative stratum | automated stratum | rule | confidence |", "|---|---|---|---|---|"] + [
     f"| {a['study_family_id']} | {rep_stratum[a['study_family_id']]} | {a['automated_stratum']} | {a['decision_rule']} | {a['confidence']} |" for a in changed]
open(os.path.join(HB, "audit", "adjudication_summary.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L[:60]))
