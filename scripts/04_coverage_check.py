r"""Check whether candidate source areas exist and whether any merged record cites them.

Writes audit\coverage_check.md. Candidate areas come from Research Ledger\REMAINING.md and the extraction passes.
"""
import glob
import json
import os

BB = r"C:\Users\lisas\OneDrive\Documents\Basketball"
APP = os.path.join(BB, "App", "Strategy")
HB = os.path.join(BB, "Research Harness Benchmark")
rows = [json.loads(l) for l in open(os.path.join(HB, "memory", "ledger_merged.jsonl"), encoding="utf-8")]
raw_all = []
for f in glob.glob(os.path.join(BB, "Research Ledger", "raw", "*.jsonl")):
    raw_all += [json.loads(l) for l in open(f, encoding="utf-8") if l.strip()]
cited = " ".join(" ".join(map(str, r.get("sources") or [])) for r in raw_all).lower()

AREAS = [
    ("App PREGAME reports", os.path.join(APP, "PREGAME_*")),
    ("App RETRO reports", os.path.join(APP, "RETRO_*")),
    ("App REPLAY reports", os.path.join(APP, "REPLAY_*")),
    ("App SCOUT reports", os.path.join(APP, "SCOUT_*")),
    ("App ADAPTATION_EXPERIMENT series files", os.path.join(APP, "ADAPTATION_EXPERIMENT_*")),
    ("App LIVE_BLOG files", os.path.join(APP, "LIVE_BLOG_*")),
    ("App demo_reports", os.path.join(APP, "demo_reports", "*")),
    ("App Chats", os.path.join(APP, "Chats", "*")),
    ("App reports", os.path.join(APP, "reports", "*")),
    ("App playsheet_validation (md)", os.path.join(APP, "playsheet_validation", "**", "*.md")),
    ("App sequence_memory outputs", os.path.join(APP, "sequence_memory", "output", "*")),
    ("App paper2_output (md/txt)", os.path.join(APP, "paper2_output", "*.[mt][dx]*")),
    ("App data series_analysis reports", os.path.join(APP, "data", "series_analysis*")),
    ("App validation scripts", os.path.join(APP, "validation", "*.py")),
    ("App top-level findings markdown", os.path.join(APP, "*findings*.md")),
    ("App top-level scripts", os.path.join(APP, "*.py")),
    ("App top-level logs", os.path.join(APP, "*.log")),
    ("connector_positive_mechanism_report", os.path.join(APP, "**", "connector_positive_mechanism_report*")),
    ("hasconn_scoring_speed_report", os.path.join(APP, "**", "hasconn_scoring_speed_report*")),
    ("Published Defensive Suppression", os.path.join(BB, "Published", "Defensive Suppression", "**", "*.*")),
    ("Published Structural Influence", os.path.join(BB, "Published", "Structural Influence", "**", "*.*")),
    ("When a Hub Sits", os.path.join(BB, "When a Hub Sits", "**", "*.*")),
    ("Team Adaptation", os.path.join(BB, "Team Adaptation", "**", "*.*")),
    ("Halftime Minutes", os.path.join(BB, "Halftime Minutes", "**", "*.*")),
    ("Lineup Adaptation", os.path.join(BB, "Lineup Adaptation", "**", "*.*")),
    ("Archive", os.path.join(BB, "Archive", "**", "*.*")),
    ("March Madness", os.path.join(r"C:\Users\lisas\OneDrive\Documents", "March Madness", "**", "*.*")),
    ("%TEMP%\\supp_audit scripts and logs", os.path.join(os.environ["TEMP"], "supp_audit", "*.*")),
    ("%TEMP%\\supp_audit subfolders", os.path.join(os.environ["TEMP"], "supp_audit", "*", "**", "*.*")),
]
DOWNLOAD_KEYS = ("nba", "basketball", "suppression", "structural", "absence", "adaptation", "cursor_")
out = ["# Coverage check (generated by scripts\\04_coverage_check.py)", "",
       "For each candidate source area: files present, and how many of those files are cited by at least one extraction "
       "record (raw slices, before merging). A file can hold experiments without being cited if a record cites a "
       "summary document instead, so low coverage marks where to look, not proof of missing experiments.", "",
       "| area | files | cited by a record | share cited | example uncited files |", "|---|---|---|---|---|"]
for name, pat in AREAS:
    files = [f for f in glob.glob(pat, recursive=True) if os.path.isfile(f) and "__pycache__" not in f
             and not f.lower().endswith((".pyc", ".parquet", ".pkl", ".png", ".jpg"))]
    hit = [f for f in files if os.path.basename(f).lower() in cited]
    unc = [os.path.basename(f) for f in files if f not in hit][:4]
    share = f"{len(hit)/len(files):.0%}" if files else "n/a"
    out.append(f"| {name} | {len(files)} | {len(hit)} | {share} | {', '.join(unc)} |")
dl = [f for f in glob.glob(os.path.join(r"C:\Users\lisas\Downloads", "*")) if os.path.isfile(f)
      and any(k in os.path.basename(f).lower() for k in DOWNLOAD_KEYS)]
hit = [f for f in dl if os.path.basename(f).lower() in cited]
share = f"{len(hit)/len(dl):.0%}" if dl else "n/a"
unc = ", ".join([os.path.basename(f) for f in dl if f not in hit][:6])
out.append(f"| Downloads files with basketball-related names | {len(dl)} | {len(hit)} | {share} | {unc} |")
open(os.path.join(HB, "audit", "coverage_check.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
