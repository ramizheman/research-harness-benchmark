r"""Write record lists by derived epistemic status and topic, plus families of repeated questions.

Reads experiment_inventory.csv (built by 01). Writes audit\status_lists.md and audit\question_families.md.
Families are a lower-threshold grouping (title/hypothesis token Jaccard >= 0.30 within one topic) of designs
that the merge kept separate; they mark repeated questions, not duplicates, and need human review.
"""
import collections
import csv
import os
import re

HB = r"C:\Users\lisas\OneDrive\Documents\Basketball\Research Harness Benchmark"
inv = list(csv.DictReader(open(os.path.join(HB, "experiment_inventory.csv"), encoding="utf-8-sig")))


def short(s, n=150):
    s = re.sub(r"\s+", " ", s or "").strip()
    return s if len(s) <= n else s[: n - 3] + "..."


out = ["# Records by derived epistemic status and topic", "",
       "Generated by scripts\\02_status_lists.py from experiment_inventory.csv. Result text is truncated; "
       "see the inventory or memory\\documents\\<id>.md for the full record.", ""]
for status in sorted({e["epistemic_status_derived"] for e in inv}):
    rows = [e for e in inv if e["epistemic_status_derived"] == status]
    out += [f"## {status} ({len(rows)})", ""]
    for topic in sorted({e["domain_topic"] for e in rows}):
        sub = [e for e in rows if e["domain_topic"] == topic]
        out += [f"### {topic} ({len(sub)})", "", "| id | title | verdict | limitation categories | result |", "|---|---|---|---|---|"]
        for e in sorted(sub, key=lambda e: e["experiment_id"]):
            lim = re.findall(r"\[([^\]]+)\]", e["power_or_reliability_limitations"])
            out.append(f"| {e['experiment_id']} | {short(e['title'], 80)} | {e['result_classification']} | "
                       f"{'; '.join(lim)[:60]} | {short(e['primary_result']).replace('|', '/')} |")
        out.append("")
open(os.path.join(HB, "audit", "status_lists.md"), "w", encoding="utf-8").write("\n".join(out))

STOP = set("a an the of to and or vs v in on for with from by its their that this is are was were be not no "
           "strategy app test".split())
tok = {e["experiment_id"]: {w for w in re.findall(r"[a-z0-9]{3,}", (e["title"] + " " + e["original_hypothesis"]).lower())
                            if w not in STOP} for e in inv}
parent = {i: i for i in tok}


def find(i):
    while parent[i] != i:
        parent[i] = parent[parent[i]]
        i = parent[i]
    return i


by_topic = collections.defaultdict(list)
for e in inv:
    by_topic[e["domain_topic"]].append(e["experiment_id"])
for ids in by_topic.values():
    for a in range(len(ids)):
        for b in range(a + 1, len(ids)):
            x, y = tok[ids[a]], tok[ids[b]]
            if len(x & y) / (len(x | y) or 1) >= 0.30:
                parent[find(ids[a])] = find(ids[b])
fam = collections.defaultdict(list)
for i in tok:
    fam[find(i)].append(i)
fams = sorted((v for v in fam.values() if len(v) >= 3), key=len, reverse=True)
E = {e["experiment_id"]: e for e in inv}
out = ["# Families of repeated questions (designs kept separate by the merge)", "",
       f"Generated by scripts\\02_status_lists.py. {len(fams)} families with 3 or more designs; "
       f"{sum(len(f) for f in fams)} designs in total. Grouping is lexical and needs human review.", ""]
for k, f in enumerate(fams, 1):
    vc = collections.Counter(E[i]["result_classification"] for i in f)
    out += [f"## F{k:02d}: {E[f[0]]['domain_topic']} ({len(f)} designs; " + ", ".join(f"{v} {c}" for v, c in vc.most_common()) + ")", "",
            "| id | date | title | verdict | status |", "|---|---|---|---|---|"]
    for i in sorted(f, key=lambda i: (E[i]["date"], i)):
        out.append(f"| {i} | {E[i]['date']} | {short(E[i]['title'], 90)} | {E[i]['result_classification']} | {E[i]['epistemic_status_derived']} |")
    out.append("")
open(os.path.join(HB, "audit", "question_families.md"), "w", encoding="utf-8").write("\n".join(out))
print(len(fams), "families;", sum(len(f) for f in fams), "designs")
for k, f in enumerate(fams, 1):
    vc = collections.Counter(E[i]["result_classification"] for i in f)
    print(f"F{k:02d}", len(f), E[f[0]]["domain_topic"][:30], dict(vc), "|", "; ".join(short(E[i]["title"], 45) for i in sorted(f)[:5]))
