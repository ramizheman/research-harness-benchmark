r"""Summaries used by the written deliverables: timeline by topic and project, source problems, and family-level splits.

Reads experiment_inventory.csv and audit\classification_flags.csv. Writes audit\summaries.md.
"""
import collections
import csv
import os
import re

HB = r"C:\Users\lisas\OneDrive\Documents\Basketball\Research Harness Benchmark"
inv = list(csv.DictReader(open(os.path.join(HB, "experiment_inventory.csv"), encoding="utf-8-sig")))
flags = {r["experiment_id"]: r["flags"] for r in csv.DictReader(open(os.path.join(HB, "audit", "classification_flags.csv"), encoding="utf-8-sig"))}
reps = [e for e in inv if e["experiment_id"] == e["study_family_representative"]]
out = ["# Summaries (generated by scripts\\03_summaries.py)", ""]


def month(d):
    m = re.match(r"(\d{4})-(\d{2})", d or "")
    return f"{m.group(1)}-{m.group(2)}" if m else "undated"


def table(title, header, rows):
    out.extend([f"## {title}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)])
    out.extend("| " + " | ".join(str(c) for c in r) + " |" for r in rows)
    out.append("")


topics = collections.Counter(e["domain_topic"] for e in reps)
rows = []
for t, n in topics.most_common():
    ds = sorted(e["date"] for e in reps if e["domain_topic"] == t and re.match(r"\d{4}-\d{2}", e["date"]))
    ms = collections.Counter(month(e["date"]) for e in reps if e["domain_topic"] == t)
    rows.append((t, n, ds[0][:10] if ds else "", ds[-1][:10] if ds else "", ", ".join(f"{m}:{c}" for m, c in sorted(ms.items()))))
table("Timeline by topic (study families)", ["topic", "families", "first dated", "last dated", "families per month"], rows)

projects = collections.Counter(e["project"] for e in reps)
rows = []
for p, n in projects.most_common():
    sub = [e for e in reps if e["project"] == p]
    ds = sorted(e["date"] for e in sub if re.match(r"\d{4}-\d{2}", e["date"]))
    vc = collections.Counter(e["result_classification"] for e in sub)
    rows.append((p, n, ds[0][:10] if ds else "", ds[-1][:10] if ds else "", ", ".join(f"{k} {c}" for k, c in vc.most_common())))
table("Projects (study families)", ["project", "families", "first dated", "last dated", "verdicts"], rows)

dates = collections.Counter(e["date_basis"] for e in inv)
table("Date basis (merged records)", ["date_basis", "records"], dates.most_common())

table("Pre-specification (study families)", ["prespecified", "families", "supported", "null/failed_gate/reversed", "artifact", "other"],
      [(p, sum(1 for e in reps if e["preregistered"] == p),
        sum(1 for e in reps if e["preregistered"] == p and e["result_classification"] == "supported"),
        sum(1 for e in reps if e["preregistered"] == p and e["result_classification"] in ("null", "failed_gate", "reversed")),
        sum(1 for e in reps if e["preregistered"] == p and e["epistemic_status_derived"] == "artifact"),
        sum(1 for e in reps if e["preregistered"] == p and e["result_classification"] not in ("supported", "null", "failed_gate", "reversed") and e["epistemic_status_derived"] != "artifact"))
       for p in ("yes", "partial", "no", "unknown")])

table("Records citing paths that do not exist", ["id", "missing / cited", "slice", "sources (truncated)"],
      [(e["experiment_id"], f"{e['source_paths_missing']}/{e['source_paths_cited']}", e["slice_file"], e["source_files_and_provenance"][:140].replace("|", "/"))
       for e in inv if int(e["source_paths_missing"] or 0) > 0])
table("Records with fewer than half of result numbers found in cited sources", ["id", "found / numbers", "slice", "title"],
      [(e["experiment_id"], f"{e['numbers_found_in_sources']}/{e['numbers_in_result']}", e["slice_file"], e["title"][:70])
       for e in inv if "result numbers found" in flags.get(e["experiment_id"], "")])
table("Records with no primary result or ambiguous status", ["id", "verdict", "failure_type", "flags"],
      [(e["experiment_id"], e["result_classification"], e["failure_type_as_recorded"], flags[e["experiment_id"]])
       for e in inv if "no primary_result" in flags.get(e["experiment_id"], "") or "ambiguous" in flags.get(e["experiment_id"], "")])
table("Verdict and failure-type inconsistencies", ["id", "verdict", "failure_type", "title"],
      [(e["experiment_id"], e["result_classification"], e["failure_type_as_recorded"], e["title"][:70]) for e in inv
       if re.search(r"C_artifact but|supported but|descriptive with", flags.get(e["experiment_id"], ""))])
slices = collections.Counter(e["slice_file"] for e in inv)
table("Merged records by extraction slice", ["slice", "records", "numbers checked", "numbers found"],
      [(s, n, sum(int(e["numbers_in_result"] or 0) for e in inv if e["slice_file"] == s),
        sum(int(e["numbers_found_in_sources"] or 0) for e in inv if e["slice_file"] == s)) for s, n in sorted(slices.items())])
table("n_runs corrections", ["id", "n_runs as extracted", "n_runs used", "reason"],
      [(e["experiment_id"], e["n_runs_as_extracted"], e["n_runs"], e["n_runs_note"]) for e in inv if e["n_runs_note"]])
open(os.path.join(HB, "audit", "summaries.md"), "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))
