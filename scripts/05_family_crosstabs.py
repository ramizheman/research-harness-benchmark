r"""Family-level topic x status table and reason categories for untestable and artifact families.

Reads experiment_inventory.csv. Writes audit\family_crosstabs.md. Reason categories are keyword rules over
failure_evidence, power_info and notes; each family can carry several.
"""
import collections
import csv
import os
import re

HB = r"C:\Users\lisas\OneDrive\Documents\Basketball\Research Harness Benchmark"
inv = list(csv.DictReader(open(os.path.join(HB, "experiment_inventory.csv"), encoding="utf-8-sig")))
reps = [e for e in inv if e["experiment_id"] == e["study_family_representative"]]
ST = ["supported", "adequately rejected (as specified)", "not tested adequately", "cannot be tested with available data",
      "artifact", "genuinely uncertain", "no hypothesis test (descriptive)", "tool evaluation", "ambiguous classification"]
out = ["# Family-level cross-tabulations (generated by scripts\\05_family_crosstabs.py)", "",
       "## Topic x derived status (study-family representatives)", "",
       "| topic | families | " + " | ".join(ST) + " |", "|" + "---|" * (len(ST) + 2)]
for t, n in collections.Counter(e["domain_topic"] for e in reps).most_common():
    out.append(f"| {t} | {n} | " + " | ".join(str(sum(1 for e in reps if e['domain_topic'] == t and e['epistemic_status_derived'] == s)) for s in ST) + " |")

REASONS = [
    ("sample or exposure too small", r"\bn\s?=\s?\d{1,2}\b|small|few|exposure|median \d+ poss|only \d+|underpowered|too thin|sparse"),
    ("measure unreliable", r"reliab|split-half|spearman-brown|\bsb\b|odd.even|noise floor|noisy"),
    ("power / MDE too large", r"\bmde\b|power"),
    ("needed data missing or unscoreable", r"missing|not available|unavailable|no .* data|0 games|unscor|could not be computed|empty|not found|pending"),
    ("confounded by team quality or talent", r"talent|team.quality|confound|strength"),
    ("label or classifier problem", r"label|classif|inferr"),
    ("selection or regression to the mean", r"regression to (the )?mean|\brtm\b|selection"),
    ("leakage", r"leak"),
    ("mechanical or construction artifact", r"mechanical|construction|shared.noise|by construction|floor"),
    ("implementation bug", r"\bbug|wrong|miscod|collision|orphan"),
]
for status in ("cannot be tested with available data", "artifact", "not tested adequately"):
    fam = [e for e in reps if e["epistemic_status_derived"] == status]
    c = collections.Counter()
    ex = collections.defaultdict(list)
    for e in fam:
        s = " ".join([e["failure_evidence"], e["power_or_reliability_limitations"], e["notes"]]).lower()
        hit = [n for n, p in REASONS if re.search(p, s)] or ["no reason category matched"]
        for h in hit:
            c[h] += 1
            ex[h].append(e["experiment_id"])
    out += ["", f"## Reason categories: {status} ({len(fam)} families)", "", "| reason | families | examples |", "|---|---|---|"]
    out += [f"| {k} | {v} | {', '.join(ex[k][:8])} |" for k, v in c.most_common()]
out += ["", "## Knowable in advance (study-family representatives)", "", "| status | yes | no | unclear | NOT RECORDED |", "|---|---|---|---|---|"]
for s in ST:
    out.append(f"| {s} | " + " | ".join(str(sum(1 for e in reps if e['epistemic_status_derived'] == s and e['knowable_in_advance'] == k)) for k in ("yes", "no", "unclear", "NOT RECORDED")) + " |")
FT = ["A_unanswerable", "B_powered_null", "C_artifact", "D_positive", "E_unclear"]
for label, pool in (("study-family representatives", reps), ("merged records", inv)):
    vc = collections.Counter(e["result_classification"] for e in pool)
    out += ["", f"## Verdict x failure type ({label})", "", "| verdict | " + " | ".join(FT) + " | total |", "|" + "---|" * (len(FT) + 2)]
    for v, n in vc.most_common():
        out.append(f"| {v} | " + " | ".join(str(sum(1 for e in pool if e['result_classification'] == v and e['failure_type_as_recorded'] == f)) for f in FT) + f" | {n} |")
    out.append("| total | " + " | ".join(str(sum(1 for e in pool if e['failure_type_as_recorded'] == f)) for f in FT) + f" | {len(pool)} |")
open(os.path.join(HB, "audit", "family_crosstabs.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
